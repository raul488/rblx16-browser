def project_sources(project: Path, prefix: str) -> list[str]:
    text = project.read_text(encoding="utf-8", errors="replace")
    out = []
    for m in re.finditer(r'<ClCompile Include="([^"]+)"', text):
        rel = m.group(1).replace("\\", "/")
        if rel.startswith("$("):
            continue
        if any(x.replace("\\", "/") in rel for x in EXCLUDE_PARTS):
            continue
        out.append(rel)
    return out


def build_index(roots: list[Path]) -> dict[str, Path]:
    index: dict[str, Path] = {}
    for root in roots:
        if not root.is_dir():
            continue
        for p in root.rglob("*"):
            if not p.is_file():
                continue
            key = p.relative_to(root).as_posix().lower()
            index.setdefault(key, p)
    return index


SOURCE_INDEX = build_index([ENGINE / "App", ENGINE / "Base", ENGINE / "Log", ENGINE / "ClientShared"])
PATCH_INDEX = build_index([PATCH])


def source_path(rel: str) -> Path:
    key = rel.replace("\\", "/").lower()
    if key.startswith("../"): key = key[3:]
    if "/" in key and key.split("/", 1)[0].lower() in ("clientshared",):
        key = key.split("/", 1)[1]
    if key in PATCH_INDEX:
        return PATCH_INDEX[key]
    if key in SOURCE_INDEX:
        return SOURCE_INDEX[key]
    return ENGINE / "App" / rel


def object_path(rel: str) -> Path:
    return OBJ / (rel + ".o")


def compile_one(args) -> tuple[str, int, str, str]:
    rel, syntax, force = args
    src = source_path(rel)
    if not src.is_file():
        # App project paths are relative to App/, Base project paths to Base/.
        base = ENGINE / "Base" / rel
        if base.is_file():
            src = base
        else:
            return rel, 1, "", f"missing source {src}"
    if not syntax and not force and object_path(rel).is_file():
        return rel, 0, "", ""
    is_c = src.suffix == ".c" and "Lua-5.1.4" not in src.as_posix() and src.name != "gpc.c"
    compiler = EMCC if is_c else EMXX
    cmd = [str(compiler)]
    if not is_c and src.suffix == ".c":
        cmd += ["-x", "c++"]
    cmd += CFLAGS if is_c else CXXFLAGS
    rel_key = rel.replace("\\", "/").lower()
    if any(part in rel_key for part in OPTIMIZED_SOURCES):
        cmd += ["-O2", "-fno-strict-aliasing"]
    for inc in INCLUDES:
        cmd += ["-I", str(inc)]
    cmd += ["-isystem", str(BOOST)]
    if syntax:
        cmd += ["-fsyntax-only"]
    else:
        obj = object_path(rel)
        obj.parent.mkdir(parents=True, exist_ok=True)
        cmd += ["-c", "-o", str(obj)]
    log = LOGS / (rel.replace("/", "_").replace("\\", "_") + ".log")
    log.parent.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["PATH"] = ("/home/raul/emsdk:/home/raul/emsdk/upstream/emscripten:"
                   "/home/raul/python312/bin:" + env.get("PATH", ""))
    env["EMSDK"] = "/home/raul/emsdk"
    env["EMSDK_NODE"] = "/home/raul/emsdk/node/24.19.0_64bit/bin/node"
    with log.open("w") as lf:
        try:
            proc = subprocess.run(cmd + [str(src)], stdout=lf, stderr=lf, timeout=600, env=env)
            rc = proc.returncode
        except subprocess.TimeoutExpired:
            rc = 124
    return rel, rc, str(log), ""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--syntax", action="store_true")
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--only", default="")
    ap.add_argument("--project", choices=["app", "base", "log", "all"], default="all")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    OBJ.mkdir(parents=True, exist_ok=True)
    LOGS.mkdir(parents=True, exist_ok=True)

    rels: list[str] = []
    if a.project in ("app", "all"):
        rels += project_sources(ENGINE / "App" / "App.vcxproj", "App")
    if a.project in ("base", "all"):
        rels += project_sources(ENGINE / "Base" / "Base.vcxproj", "Base")
    if a.project in ("log", "all"):
        rels += ["FastLog.cpp", "FastLogStream.cpp"]

    if a.only:
        rels = [r for r in rels if a.only.lower() in r.lower()]
    if a.limit:
        rels = rels[: a.limit]

    print(f"sources: {len(rels)}  syntax={a.syntax}  jobs={a.jobs}", flush=True)
    tasks = [(r, a.syntax, a.force) for r in rels]
    failures = []
    done = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=a.jobs) as ex:
        futures = {ex.submit(compile_one, t): t for t in tasks}
        for fut in concurrent.futures.as_completed(futures):
            rel, rc, log, err = fut.result()
            done += 1
            if rc != 0:
                failures.append((rel, rc, log, err))
                print(f"FAIL {rel}  ({log})", flush=True)
            if done % 20 == 0 or done == len(tasks):
                print(f"  {done}/{len(tasks)}", flush=True)
    print(f"\n{len(tasks) - len(failures)}/{len(tasks)} OK, {len(failures)} failed", flush=True)
    (OUT / "build-result.json").write_text(json.dumps(
        {"sources": rels, "failures": failures, "syntax": a.syntax}, indent=2))
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
